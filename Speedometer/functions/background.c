void cyclist_draw_frame(uint8_t frame, uint8_t page, uint8_t col)
{
    uint8_t p;
    uint8_t x;
    uint8_t bg;
    uint8_t sprite;
    uint8_t out;

    if (frame >= CYCLIST_FRAMES)
    {
        frame = 0;
    }

    if (page > (OLED_PAGES - CYCLIST_PAGES))
    {
        return;
    }

    for (p = 0; p < CYCLIST_PAGES; p++)
    {
        oled_set_pos((uint8_t)(page + p), col);

        for (x = 0; x < CYCLIST_W; x++)
        {
            /* page 4..7 on screen corresponds to page 0..3 in bg_bottom */
            bg = bg_sample_bottom((uint8_t)((page - 4) + p),
            (int16_t)(col + x) + bg_bottom_x);

            sprite = pgm_read_byte(&cyclist_frames[frame][p][x]);

            /* Transparent draw: only turn ON pixels */
            out = bg | sprite;

            oled_data(out);
        }
    }
}

