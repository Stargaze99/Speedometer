static uint8_t bg_wrap_sample(const uint8_t layer[4][128], uint8_t page, int16_t x)
{
    while (x < 0)
    {
        x += 128;
    }

    while (x >= 128)
    {
        x -= 128;
    }

    return pgm_read_byte(&layer[page][x]);
}

uint8_t bg_sample_top(uint8_t page, int16_t x)
{
    return bg_wrap_sample(bg_top, page, x);
}

uint8_t bg_sample_bottom(uint8_t page, int16_t x)
{
    return bg_wrap_sample(bg_bottom, page, x);
}

void bg_draw_parallax(int16_t top_x, int16_t bottom_x)
{
    uint8_t page;
    uint8_t col;

    /* Upper 32 px = pages 0..3 */
    for (page = 0; page < BG_TOP_PAGES; page++)
    {
        oled_set_pos(page, 0);

        for (col = 0; col < BG_TILE_WIDTH; col++)
        {
            oled_data(bg_sample_top(page, (int16_t)col + top_x));
        }
    }

    /* Lower 32 px = pages 4..7 */
    for (page = 0; page < BG_BOTTOM_PAGES; page++)
    {
        oled_set_pos((uint8_t)(page + 4), 0);

        for (col = 0; col < BG_TILE_WIDTH; col++)
        {
            oled_data(bg_sample_bottom(page, (int16_t)col + bottom_x));
        }
    }
}

void bg_update_speed(void)
{
    if (gps_data.speed_kmh_x10 == 0)
    {
        bg_speed_level = 0;
    }
    else if (gps_data.speed_kmh_x10 < 50)      /* under 5.0 km/h */
    {
        bg_speed_level = 1;
    }
    else if (gps_data.speed_kmh_x10 < 120)     /* under 12.0 km/h */
    {
        bg_speed_level = 2;
    }
    else if (gps_data.speed_kmh_x10 < 220)     /* under 22.0 km/h */
    {
        bg_speed_level = 3;
    }
    else
    {
        bg_speed_level = 4;
    }
}

void bg_draw(void)
{
    uint8_t top_step = 0;
    uint8_t bottom_step = 0;

    switch (bg_speed_level)
    {
        case 0:
        top_step = 0;
        bottom_step = 0;
        break;

        case 1:
        top_step = 1;
        bottom_step = 1;
        break;

        case 2:
        top_step = 1;
        bottom_step = 2;
        break;

        case 3:
        top_step = 2;
        bottom_step = 3;
        break;

        case 4:
        top_step = 2;
        bottom_step = 4;
        break;

        default:
        top_step = 1;
        bottom_step = 2;
        break;
    }

    /* Increase offset to move image right-to-left on screen */
    bg_top_x += top_step;
    if (bg_top_x >= 128)
    {
        bg_top_x -= 128;
    }

    bg_bottom_x += bottom_step;
    if (bg_bottom_x >= 128)
    {
        bg_bottom_x -= 128;
    }

    bg_draw_parallax(bg_top_x, bg_bottom_x);
}

void oled_write_2digit(uint8_t value)
{
    oled_write_char((char)('0' + (value / 10)));
    oled_write_char((char)('0' + (value % 10)));
}

void draw_gps_info(void)
{
    uint16_t speed_whole;
    uint8_t speed_frac;

    speed_whole = gps_data.speed_kmh_x10 / 10;
    speed_frac  = (uint8_t)(gps_data.speed_kmh_x10 % 10);

    /* Speed */
    oled_set_pos(5, 35);

    /* Example: 12.3 km/h */
    if (speed_whole >= 100)
    {
        oled_write_char((char)('0' + ((speed_whole / 100) % 10)));
    }
    if (speed_whole >= 10)
    {
        oled_write_char((char)('0' + ((speed_whole / 10) % 10)));
    }
    oled_write_char((char)('0' + (speed_whole % 10)));
    oled_write_char('!');
    oled_write_char((char)('0' + speed_frac));
    oled_write_string(" km/h");

    /* Time */
    oled_set_pos(6, 40);
    oled_write_2digit((gps_data.time.hour + 2));
    oled_write_char(';');
    oled_write_2digit(gps_data.time.minute);
}